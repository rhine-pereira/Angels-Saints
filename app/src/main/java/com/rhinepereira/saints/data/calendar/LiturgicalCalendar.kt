package com.rhinepereira.saints.data.calendar

import android.content.res.AssetManager
import org.json.JSONArray
import java.time.LocalDate
import java.util.concurrent.ConcurrentHashMap

enum class Vestment { GREEN, PURPLE, WHITE, RED, ROSE, BLACK, GOLD }
enum class Season { ADVENT, CHRISTMAS, LENT, PASCHAL_TRIDUUM, EASTER, ORDINARY_TIME }
enum class Rank { SOLEMNITY, SUNDAY, FEAST, MEMORIAL, OPTIONAL_MEMORIAL, WEEKDAY }

data class LiturgicalDay(
    val date: LocalDate,
    val title: String,
    val rank: Rank,
    val vestment: Vestment,
    val season: Season,
    val week: Int,
    val others: List<String>
)

/** A contiguous run of days in one season, e.g. Ordinary Time after Pentecost. */
data class SeasonSpan(val season: Season, val start: LocalDate, val end: LocalDate)

data class Saint(val name: String, val title: String, val month: Int, val day: Int)

/**
 * Season engine. Reads the romcal-generated India calendar bundled in assets/calendar
 * (one YYYY.json per year, regenerated by tools/calendar-gen).
 */
class LiturgicalCalendar(private val assets: AssetManager) {

    private val years = ConcurrentHashMap<Int, List<LiturgicalDay>>()

    val availableYears: IntRange by lazy {
        val ys = assets.list("calendar").orEmpty()
            .mapNotNull { it.removeSuffix(".json").toIntOrNull() }
        if (ys.isEmpty()) IntRange.EMPTY else ys.min()..ys.max()
    }

    val saints: List<Saint> by lazy {
        val arr = JSONArray(assets.open("calendar/saints.json").bufferedReader().use { it.readText() })
        List(arr.length()) { i ->
            val o = arr.getJSONObject(i)
            Saint(o.getString("n"), o.getString("t"), o.getInt("m"), o.getInt("day"))
        }
    }

    fun year(year: Int): List<LiturgicalDay> = years.getOrPut(year) {
        if (year !in availableYears) return emptyList()
        val arr = JSONArray(assets.open("calendar/$year.json").bufferedReader().use { it.readText() })
        List(arr.length()) { i ->
            val o = arr.getJSONObject(i)
            val others = o.optJSONArray("o")
            LiturgicalDay(
                date = LocalDate.parse(o.getString("d")),
                title = o.getString("t"),
                rank = enumOr(o.getString("r"), Rank.WEEKDAY),
                vestment = enumOr(o.getString("c"), Vestment.GREEN),
                season = enumOr(o.getString("s"), Season.ORDINARY_TIME),
                week = o.optInt("w", 0),
                others = if (others == null) emptyList() else List(others.length()) { others.getString(it) }
            )
        }
    }

    fun day(date: LocalDate): LiturgicalDay? = year(date.year).getOrNull(date.dayOfYear - 1)

    fun spans(year: Int): List<SeasonSpan> {
        val days = year(year)
        val spans = mutableListOf<SeasonSpan>()
        for (d in days) {
            val last = spans.lastOrNull()
            if (last != null && last.season == d.season) {
                spans[spans.lastIndex] = last.copy(end = d.date)
            } else {
                spans += SeasonSpan(d.season, d.date, d.date)
            }
        }
        return spans
    }

    /** First day after [from] whose season differs from [from]'s, looking into next year if needed. */
    fun nextSeason(from: LocalDate): LiturgicalDay? {
        val current = day(from)?.season ?: return null
        return (year(from.year).drop(from.dayOfYear) + year(from.year + 1))
            .firstOrNull { it.season != current }
    }

    private inline fun <reified E : Enum<E>> enumOr(name: String, fallback: E): E =
        runCatching { enumValueOf<E>(name) }.getOrDefault(fallback)
}
